// Generates SQL to seed local D1 with test data (clients, projects, invoices, tickets).
// Not run automatically — output is piped into `wrangler d1 execute --local`.
import { randomUUID, webcrypto } from "node:crypto";

const PASSWORD_ITERATIONS = 100_000;

function toBase64(bytes) {
  return Buffer.from(bytes).toString("base64");
}

async function hashPassword(password) {
  const salt = webcrypto.getRandomValues(new Uint8Array(16));
  const keyMaterial = await webcrypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(password),
    "PBKDF2",
    false,
    ["deriveBits"]
  );
  const bits = await webcrypto.subtle.deriveBits(
    { name: "PBKDF2", hash: "SHA-256", salt, iterations: PASSWORD_ITERATIONS },
    keyMaterial,
    256
  );
  return `pbkdf2$${PASSWORD_ITERATIONS}$${toBase64(salt)}$${toBase64(new Uint8Array(bits))}`;
}

function esc(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insert(table, cols, rows) {
  return rows
    .map((row) => `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${row.map(esc).join(", ")});`)
    .join("\n");
}

const now = Date.now();
const day = 86_400_000;

const clients = [
  { company: "Riverside Roasters", contact: "Maya Chen", email: "maya@riversideroasters.test", phone: "419-555-0142" },
  { company: "Harbor Light Legal", contact: "Owen Baptiste", email: "owen@harborlightlegal.test", phone: "419-555-0198" },
];

const userRows = [];
const clientRows = [];
const projectRows = [];
const taskRows = [];
const projectNoteRows = [];
const taskNoteRows = [];
const timeRows = [];
const invoiceRows = [];
const ticketRows = [];
const messageRows = [];

let out = [];
out.push("-- Local dev test data. Generated by scripts/seed-local.mjs — do not run against remote.");

const adminId = randomUUID();
userRows.push([adminId, "admin@example.test", await hashPassword("test-password-123"), "admin", 1, now]);

for (const c of clients) {
  const userId = randomUUID();
  const clientId = randomUUID();
  const passwordHash = await hashPassword("test-password-123");

  userRows.push([userId, c.email, passwordHash, "client", 1, now]);
  clientRows.push([clientId, userId, c.company, c.contact, c.phone, now]);

  const projectId = randomUUID();
  projectRows.push([
    projectId,
    clientId,
    `${c.company} Website Refresh`,
    "Redesign and CMS migration.",
    "in_progress",
    now - 14 * day,
    now + 30 * day,
    now - 14 * day,
    now,
  ]);

  const lanes = ["planning", "to_do", "in_progress", "qa", "done"];
  const titles = ["Plan launch", "CMS integration", "Contact form", "Review accessibility", "Homepage design"];
  for (const [index, lane] of lanes.entries()) {
    const taskId = randomUUID();
    taskRows.push([taskId, projectId, titles[index], null, index === 3 ? "bug" : "task", lane,
      index === 2 ? "high" : "normal", adminId, now - 5 * day, now]);
    if (index < 2) {
      taskNoteRows.push([randomUUID(), taskId, adminId, "Review this with the client.", now, now]);
      timeRows.push([randomUUID(), taskId, adminId, 45 + index * 30, now - day, "Project work", now]);
    }
  }
  projectNoteRows.push([randomUUID(), projectId, adminId, "Kickoff completed with the client.", now, now]);

  for (const [index, status] of ["draft", "sent", "paid", "overdue", "void"].entries()) {
    invoiceRows.push([randomUUID(), clientId, `Milestone ${index + 1}`, 100000 + index * 25000, status,
      now - 20 * day, now - 5 * day, status === "paid" ? now - 8 * day : null, now - 20 * day, now]);
  }

  for (const status of ["open", "in_progress", "waiting_on_client", "resolved", "closed"]) {
    const ticketId = randomUUID();
    ticketRows.push([ticketId, clientId, `Website question (${status})`, status, "normal", now - 2 * day, now]);
    messageRows.push([randomUUID(), ticketId, userId, "Could we discuss an update to the website?", now - 2 * day]);
  }
}

out.push(insert("users", ["id", "email", "password_hash", "role", "is_active", "created_at"], userRows));
out.push(insert("clients", ["id", "user_id", "company_name", "contact_name", "phone", "created_at"], clientRows));
out.push(
  insert(
    "projects",
    ["id", "client_id", "name", "description", "status", "start_date", "target_date", "created_at", "updated_at"],
    projectRows
  )
);
out.push(insert("tasks", ["id", "project_id", "title", "description", "type", "lane", "priority", "assigned_to_user_id", "created_at", "updated_at"], taskRows));
out.push(insert("project_notes", ["id", "project_id", "author_user_id", "body", "created_at", "updated_at"], projectNoteRows));
out.push(insert("task_notes", ["id", "task_id", "author_user_id", "body", "created_at", "updated_at"], taskNoteRows));
out.push(insert("time_entries", ["id", "task_id", "user_id", "minutes", "entry_date", "note", "created_at"], timeRows));
out.push(
  insert(
    "invoices",
    ["id", "client_id", "description", "amount_cents", "status", "issued_date", "due_date", "paid_date", "created_at", "updated_at"],
    invoiceRows
  )
);
out.push(insert("tickets", ["id", "client_id", "subject", "status", "priority", "created_at", "updated_at"], ticketRows));
out.push(insert("ticket_messages", ["id", "ticket_id", "author_user_id", "body", "created_at"], messageRows));

